// Helper to generate BibTeX for any publication
function getBibTeX(pub) {
  const authorLastName = pub.authors.split(',')[0].trim().split(' ').pop();
  const citeKey = `${authorLastName.toLowerCase()}${pub.year}${pub.title.split(' ')[0].toLowerCase().replace(/[^a-z0-9]/g, '')}`;
  return `@article{${citeKey},
  title = {${pub.title}},
  author = {${pub.authors}},
  journal = {${pub.journal}},
  year = {${pub.year}},
  volume = {${pub.volume || ''}},
  number = {${pub.issue || ''}},
  pages = {${pub.pages || ''}},
  doi = {${pub.doi || ''}},
  url = {${pub.url || ''}}
}`;
}

